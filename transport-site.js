let currentLang=localStorage.getItem("aridesLang")||"et";
const $=(s,r=document)=>r.querySelector(s);
const $$=(s,r=document)=>[...r.querySelectorAll(s)];
function applyLang(lang){
  if(!I18N[lang]) lang="et";
  currentLang=lang;localStorage.setItem("aridesLang",lang);
  document.documentElement.lang=lang;document.title=I18N[lang].title;
  const meta=$('meta[name="description"]');if(meta)meta.content=I18N[lang].desc;
  $$("[data-i18n]").forEach(el=>{const k=el.dataset.i18n;if(I18N[lang][k]!=null)el.textContent=I18N[lang][k]});
  $$("[data-i18n-placeholder]").forEach(el=>{const k=el.dataset.i18nPlaceholder;if(I18N[lang][k]!=null)el.placeholder=I18N[lang][k]});
  $$(".lang-btn").forEach(b=>b.classList.toggle("active",b.dataset.lang===lang));
}
function selectService(value){
  const sel=$("#service");if(sel){sel.value=value;sel.dispatchEvent(new Event("change"))}
  $("#order")?.scrollIntoView({behavior:"smooth",block:"center"});
}
function whatsappMessage(){
  const from=$("#from")?.value.trim()||"";
  const to=$("#to")?.value.trim()||"";
  const service=$("#service");
  const serviceText=service?.options[service.selectedIndex]?.text||"";
  const labels={
    et:`Tere! Soovin tellida veo.\nTeenus: ${serviceText}\nKust: ${from}\nKuhu: ${to}`,
    ru:`Здравствуйте! Хочу заказать перевозку.\nУслуга: ${serviceText}\nОткуда: ${from}\nКуда: ${to}`,
    en:`Hello! I would like to book transport.\nService: ${serviceText}\nFrom: ${from}\nTo: ${to}`
  };
  return labels[currentLang]||labels.et;
}
