  const supported = ["et", "ru", "en", "fi"];
  const LS_KEY = "lang";
  const localeMap = {
    et: "et-EE",
    ru: "ru-RU",
    en: "en-GB",
    fi: "fi-FI"
  };

  let refreshGalleryText = () => {};

  const $ = (sel, root = document) => root.querySelector(sel);
  const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));

  function detectLang() {
    const saved = localStorage.getItem(LS_KEY);
    if (saved && supported.includes(saved)) return saved;

    const langs = (navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language]
    ).filter(Boolean);

    const first = (langs[0] || "et").toLowerCase();
    if (first.startsWith("ru")) return "ru";
    if (first.startsWith("en")) return "en";
    if (first.startsWith("fi")) return "fi";
    return "et";
  }

  function v(lang, key) {
    const dict = i18n[lang] || i18n.et;
    return dict[key] ?? i18n.et[key] ?? "";
  }

  function t(lang, key) {
    const value = v(lang, key);
    return typeof value === "string" ? value : "";
  }

  function getLocale(lang) {
    return localeMap[lang] || localeMap.et;
  }

  function applyNativeLocale(lang) {
    const locale = getLocale(lang);
    document.documentElement.lang = locale;
    document.body?.setAttribute("lang", locale);

    $$("form, input, select, textarea, button").forEach((el) => {
      el.setAttribute("lang", locale);
    });
  }

  function applyLang(lang) {
    applyNativeLocale(lang);
    document.documentElement.setAttribute("data-site-lang", lang);
    localStorage.setItem(LS_KEY, lang);

    const label = $("#langLabel");
    if (label) label.textContent = lang.toUpperCase();

    $$("[data-i18n]").forEach((el) => {
      el.textContent = t(lang, el.getAttribute("data-i18n"));
    });

    $$("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", t(lang, el.getAttribute("data-i18n-ph")));
    });

    $$("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", t(lang, el.getAttribute("data-i18n-alt")));
    });

    document.title = t(lang, "metaTitle");
    const metaDescription = $('meta[name="description"]');
    if (metaDescription) metaDescription.setAttribute("content", t(lang, "metaDescription"));

    syncLangBlocks(lang);
    refreshGalleryText();
  }

  function syncLangBlocks(lang) {
    $$("[data-lang-block]").forEach((el) => {
      el.hidden = el.getAttribute("data-lang-block") !== lang;
    });
  }

  function initLegalModal(langGetter) {
    const modal = $("#legalModal");
    const closeBtn = $("#legalClose");
    const tabs = $$("[data-legal-tab]", modal);
    const sections = $$("[data-legal-section]", modal);
    const openers = $$("[data-legal-open]");
    if (!modal || !closeBtn || !tabs.length || !sections.length) return;

    const setSection = (sectionId) => {
      const target = sectionId || "privacy";
      tabs.forEach((tab) => {
        const active = tab.getAttribute("data-legal-tab") === target;
        tab.classList.toggle("is-active", active);
        tab.setAttribute("aria-selected", String(active));
      });
      sections.forEach((section) => {
        const active = section.getAttribute("data-legal-section") === target;
        section.classList.toggle("is-active", active);
        section.hidden = !active;
      });
    };

    const open = (sectionId) => {
      setSection(sectionId);
      syncLangBlocks(langGetter());
      modal.classList.add("open");
      modal.setAttribute("aria-hidden", "false");
      document.body.style.overflow = "hidden";
    };

    const close = () => {
      modal.classList.remove("open");
      modal.setAttribute("aria-hidden", "true");
      document.body.style.overflow = "";
    };

    openers.forEach((opener) => {
      opener.addEventListener("click", (e) => {
        e.preventDefault();
        open(opener.getAttribute("data-legal-open"));
      });
    });

    tabs.forEach((tab) => {
      tab.addEventListener("click", () => {
        setSection(tab.getAttribute("data-legal-tab"));
      });
    });

    closeBtn.addEventListener("click", close);
    modal.addEventListener("click", (e) => {
      if (e.target === modal) close();
    });
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape" && modal.classList.contains("open")) close();
    });
  }

  function initGallery() {
    const cards = $$(".galleryCard");
    const modal = $("#galleryModal");
    const closeBtn = $("#modalClose");
    const prevBtn = $("#modalPrev");
    const nextBtn = $("#modalNext");
    const image = $("#modalImage");
    const caption = $("#modalCaption");
    const counter = $("#modalCounter");
    if (!cards.length || !modal || !closeBtn || !prevBtn || !nextBtn || !image || !caption || !counter) return;

    const slides = cards.map((card) => {
      const img = $("img", card);
      const captionEl = $("figcaption", card);
      return {
        src: img?.getAttribute("src") || "",
        alt: img?.getAttribute("alt") || captionEl?.textContent?.trim() || "Gallery image",
        caption: captionEl?.textContent?.trim() || ""
      };
    });

    let currentIndex = 0;

    const render = () => {
      const slide = slides[currentIndex];
      if (!slide) return;
      image.src = slide.src;
      image.alt = slide.alt || "Gallery image";
      caption.textContent = slide.caption;
      counter.textContent = `${currentIndex + 1} / ${slides.length}`;
    };

    const openAt = (index) => {
      currentIndex = (index + slides.length) % slides.length;
      render();
      modal.classList.add("open");
      modal.setAttribute("aria-hidden", "false");
      document.body.style.overflow = "hidden";
    };

    const close = () => {
      modal.classList.remove("open");
      modal.setAttribute("aria-hidden", "true");
      document.body.style.overflow = "";
      image.removeAttribute("src");
    };

    const move = (delta) => {
      currentIndex = (currentIndex + delta + slides.length) % slides.length;
      render();
    };

    cards.forEach((card, index) => {
      card.addEventListener("click", () => openAt(index));
      card.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          openAt(index);
        }
      });
    });

    closeBtn.addEventListener("click", close);
    prevBtn.addEventListener("click", () => move(-1));
    nextBtn.addEventListener("click", () => move(1));
    modal.addEventListener("click", (e) => {
      if (e.target === modal) close();
    });
    document.addEventListener("keydown", (e) => {
      if (!modal.classList.contains("open")) return;
      if (e.key === "Escape") close();
      if (e.key === "ArrowLeft") move(-1);
      if (e.key === "ArrowRight") move(1);
    });

    refreshGalleryText = () => {
      if (modal.classList.contains("open")) render();
    };
  }

  function initSmoothScroll() {
    $$('a[href^="#"]').forEach((link) => {
      link.addEventListener("click", (e) => {
        const href = link.getAttribute("href");
        if (!href || href === "#") return;
        const target = document.querySelector(href);
        if (!target) return;
        e.preventDefault();
        target.scrollIntoView({ behavior: "smooth", block: "start" });
      });
    });
  }

  document.addEventListener("DOMContentLoaded", () => {
    let currentLang = detectLang();
    const getLang = () => localStorage.getItem(LS_KEY) || currentLang;

    initLangMenu();
    initGallery(getLang);
    initLegalModal(getLang);
    initSmoothScroll();
    applyLang(currentLang);

    $("#langMenu")?.addEventListener("click", (e) => {
      const target = e.target.closest("button[data-lang]");
      if (!target) return;
      currentLang = target.getAttribute("data-lang") || currentLang;
    });
  });
